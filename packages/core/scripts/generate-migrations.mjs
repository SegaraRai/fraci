import { execFileSync } from "node:child_process";
import { mkdir, rm, writeFile } from "node:fs/promises";

const run = (...args) =>
  execFileSync("vp", ["exec", ...args], {
    env: process.env,
    stdio: "inherit",
  });
const capture = (...args) =>
  execFileSync("vp", ["exec", ...args], {
    encoding: "utf8",
    env: process.env,
    stdio: ["ignore", "pipe", "inherit"],
  });

await rm("drizzle/migrations", { force: true, recursive: true });
run("drizzle-kit", "generate", "--config=drizzle.config.ts", "--name", "init");

await rm("drizzle/migrations.e2e-binary", { force: true, recursive: true });
run(
  "drizzle-kit",
  "generate",
  "--config=drizzle.e2e-binary.config.ts",
  "--name",
  "init",
);

await rm("drizzle/migrations.e2e-string", { force: true, recursive: true });
run(
  "drizzle-kit",
  "generate",
  "--config=drizzle.e2e-string.config.ts",
  "--name",
  "init",
);

await rm("prisma/migrations", { force: true, recursive: true });
const prismaMigrationDir = "prisma/migrations/20250319122555_init";
await mkdir(prismaMigrationDir, { recursive: true });
await writeFile(
  `${prismaMigrationDir}/migration.sql`,
  `${capture(
    "prisma",
    "migrate",
    "diff",
    "--from-empty",
    "--to-schema",
    "prisma/schema.prisma",
    "--script",
  ).trimEnd()}\n`,
);
await writeFile(
  "prisma/migrations/migration_lock.toml",
  [
    "# Please do not edit this file manually",
    "# It should be added in your version-control system (e.g., Git)",
    'provider = "sqlite"',
    "",
  ].join("\n"),
);
run("prisma", "generate");
